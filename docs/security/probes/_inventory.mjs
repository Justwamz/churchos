// Builds docs/security/route-inventory.md from the route sources (static) and, if present, authz-matrix.results.json (dynamic).
//   node docs/security/probes/_inventory.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extract } from './_extract-routes.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../..');
const routesDir = path.join(root, 'apps/api/src/routes');
const authSrc = fs.readFileSync(path.join(root, 'apps/api/src/auth.ts'), 'utf8');
const PERMS = [...authSrc.matchAll(/^  '([a-z]+\.[a-z]+)',$/gm)].map((m) => m[1]);
const permRe = new RegExp(`'(${PERMS.map((p) => p.replace('.', '\.')).join('|')})'`, 'g');

const routes = extract();
const fileSrc = new Map();
const lines = (f) => { if (!fileSrc.has(f)) fileSrc.set(f, fs.readFileSync(path.join(routesDir, f), 'utf8').split('\n')); return fileSrc.get(f); };
// helper functions defined in a file and the permissions they check
function helperPerms(f) {
  const text = lines(f).join('\n'); const out = new Map();
  const re = /(?:^|\n)\s*(?:export\s+)?(?:async\s+function|function|const)\s+([A-Za-z][A-Za-z0-9_]{2,})\s*(?:=\s*(?:async\s*)?\(|\()/g;
  let m;
  while ((m = re.exec(text))) {
    const start = text.indexOf('{', m.index + m[0].length); if (start < 0) continue;
    let depth = 0, i = start; for (; i < text.length; i++) { if (text[i] === '{') depth++; else if (text[i] === '}') { depth--; if (!depth) break; } }
    const body = text.slice(start, i + 1);
    if (/app\.(get|post|put|patch|delete)\(/.test(body)) continue;
    const ps = [...new Set([...body.matchAll(permRe)].map((x) => x[1]))];
    const scope = [];
    for (const k of ['inStaffScope', 'staffScope', 'grantsFor', 'branchesFor']) if (body.includes(k)) scope.push(k);
    if (ps.length || scope.length) out.set(m[1], { ps, scope });
  }
  return out;
}
const matrix = fs.existsSync(path.join(here, 'authz-matrix.results.json')) ? JSON.parse(fs.readFileSync(path.join(here, 'authz-matrix.results.json'), 'utf8')) : null;
const byRoute = new Map();
if (matrix) for (const x of matrix.results) { const k = `${x.method} ${x.route}`; (byRoute.get(k) ?? byRoute.set(k, []).get(k)).push(x); }

const rows = [];
for (const r of routes) {
  const L = lines(r.file);
  let body = ''; for (let i = r.line - 1; i < Math.min(L.length, r.line + 70); i++) { if (i > r.line - 1 && /^\s*app\.(get|post|put|patch|delete)\(/.test(L[i])) break; body += L[i] + '\n'; }
  const hp = helperPerms(r.file);
  const perms = new Set([...body.matchAll(permRe)].map((m) => m[1]));
  const scope = new Set();
  if (/inStaffScope/.test(body)) scope.add('inStaffScope');
  if (/staffScope/.test(body)) scope.add('staffScope');
  if (/grantsFor/.test(body)) scope.add('grantsFor');
  if (/branchesFor/.test(body)) scope.add('branchesFor');
  if (/audienceOf|scopedAudience/.test(body)) scope.add('audience check');
  if (/asOrg/.test(body)) scope.add('RLS');
  if (/user_id\s*=\s*\$\d|=\s*\$\d\s+AND\s+user_id|requester_id\s*=\s*\$|buyer_user_id\s*=\s*\$|recorded_by\s*!==?|\.uid\b/.test(body)) scope.add('owner=uid');
  if (/org_id\s*=\s*\$\d|org_id\s*!==?|\.org_id\s*===/.test(body)) scope.add('org_id');
  for (const [name, v] of hp) if (body.includes(`${name}(`)) { v.ps.forEach((p) => perms.add(p)); v.scope.forEach((s) => scope.add(s + ' (helper ' + name + ')')); }
  const params = (r.path.match(/:[A-Za-z]+/g) ?? []).length;
  const att = byRoute.get(`${r.method} ${r.path}`) ?? [];
  const attackers = att.filter((x) => x.persona !== 'anon' && x.mode === 'victim' && (x.why === 'other tenant' || x.why === "another person's object" || x.why === 'no staff role'));
  const denied = attackers.filter((x) => [401, 403, 404].includes(x.status)).length;
  const incon = attackers.filter((x) => x.inconclusive).length;
  const anon = att.find((x) => x.persona === 'anon');
  let dyn = '-';
  if (r.auth === 'public') dyn = 'public (see authz-public.mjs)';
  else if (att.length) dyn = `anon ${anon?.status ?? '-'}; ${attackers.length ? `outsiders ${denied}/${attackers.length} denied${incon ? `, ${incon} inconclusive (400/409)` : ''}` : params ? 'no object fixture for outsiders' : 'n/a'}`;
  rows.push({ ...r, perms: [...perms].sort(), scope: [...scope], params, dyn });
}
const esc = (s) => String(s).replace(/\|/g, '\|');
const by = (a) => routes.filter((r) => r.auth === a).length;
let md = `# ChurchOS API route inventory\n\nGenerated by \`docs/security/probes/_inventory.mjs\` from \`apps/api/src/routes/*.ts\` (static read) and the last run of \`authz-matrix.mjs\` (dynamic). Guard, permission and scope columns are derived from the handler source and the helpers it calls, so treat them as a map for review, not as proof: the proof is the matrix result column.\n\n`;
md += `**Totals:** ${routes.length} routes (${by('public')} public or webhook, ${by('session')} signed-in, ${by('admin')} platform-admin). Templated routes (\`/adverts/:id/\${verb}\`, \`/me/adverts/:id/\${kind}\`, \`/webhooks/daraja/:token/\${kind}\`) are expanded to their real paths.\n\n`;
md += `Legend. **Guard**: \`public\` = no sign-in; \`session\` = \`requireSession\`; \`admin\` = \`requireAdmin\`. **Scope / ownership**: \`inStaffScope\` (object's org+branch against the caller's grants for a permission), \`staffScope\`/\`grantsFor\`/\`branchesFor\` (caller's branches for a permission, used to filter queries), \`owner=uid\` (query is restricted to the signed-in user's own rows), \`org_id\` (query restricted to a church), \`RLS\` (runs through \`db.asOrg\`, enforced by the database). **Matrix**: result of \`authz-matrix.mjs\` for this route: anonymous status, and how many requests from other churches / other branches / people without the role were denied (401/403/404).\n\n`;
md += `| # | Method | Path | Guard | Permission(s) checked | Scope / ownership checks | Matrix | Source |\n|---|---|---|---|---|---|---|---|\n`;
rows.forEach((r, i) => { md += `| ${i + 1} | ${r.method} | \`${esc(r.path)}\` | ${r.auth.startsWith('config') ? 'public (webhook)' : r.auth} | ${r.perms.length ? r.perms.join(', ') : (r.auth === 'public' ? '-' : r.auth === 'admin' ? 'platform admin' : 'none (own data / any signed-in user)')} | ${r.scope.length ? esc(r.scope.join(', ')) : '-'} | ${esc(r.dyn)} | ${r.file}:${r.line} |\n`; });
const notes = path.join(here, '_inventory-notes.md');
if (fs.existsSync(notes)) md += fs.readFileSync(notes, 'utf8');
md = md.replace('so treat them as a map for review, not as proof', 'so treat them as a map for review, not as proof (a permission string that appears in a handler for another reason, for example in a message, is listed too)');
fs.writeFileSync(path.join(root, 'docs/security/route-inventory.md'), md);
console.log(`wrote route-inventory.md with ${rows.length} rows`);
// a few lists for the findings
const noPermNoScope = rows.filter((r) => r.auth === 'session' && !r.perms.length && !r.scope.length);
console.log('session routes with no permission and no scope signal:', noPermNoScope.length);
for (const r of noPermNoScope) console.log('  ', r.method, r.path, r.file + ':' + r.line);
